
from typing import Protocol
import cairo

class iColor(Protocol):
    r:float
    g:float
    b:float
    a:float
    values: tuple[float,float, float,float]    

class iCFont(Protocol):
    name:str
    size:int
    slant:cairo.FontSlant
    weight:cairo.FontWeight


class iBoard(Protocol):
    dimension: tuple[int, int]
    point_size:float
    border_size:float
    surface:cairo.ImageSurface

    def setup(self):...
    def fill_drag(self) -> None:...
    def fill(self)-> None:...
    def ink(self)-> None:...
    def fill_ink(self, ink_color:iColor, brd_size:float)->None:...
    def set_origin(self, x:int, y:int)->None: ...
    def set_scale(self, scale_fac_x:float, scale_fac_y:float)->None:...
    def set_font(self, font:iCFont)->None:...
    def set_color(self, color:iColor)->None:...
    def set_width(self, brd)->None:...
    def lift(self,x,y)->None:...
    def start_drag(self)->None:...
    def finish_drag(self)->None:... 
    def translate(self, x:int, y:int)->None:...
    def rotate(self, degrees:float)->None:...
    def modify_basis(self, pivot:tuple[int, int], scale:int, rotation:float)-> None:...
    def render_image(self)->cairo.Surface:...
    

